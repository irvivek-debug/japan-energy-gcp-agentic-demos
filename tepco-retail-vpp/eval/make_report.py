"""Build docs/EVAL_REPORT.md (and the README eval block) from eval/results/*.json. Denominators come from the result
files, never from hand-typed numbers. Usage: python eval/make_report.py "<pytest summary line>" [notes.md]"""
from __future__ import annotations

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "eval", "results")


def load(name):
    p = os.path.join(RES, name)
    return json.load(open(p)) if os.path.exists(p) else None


def main() -> None:
    pytest_line = sys.argv[1] if len(sys.argv) > 1 else "(not recorded)"
    notes = open(sys.argv[2]).read() if len(sys.argv) > 2 and os.path.exists(sys.argv[2]) else ""
    adk, gr, sf = load("adk_summary.json") or {}, load("grounding_results.json"), load("safety_results.json")
    L = ["# Evaluation report", "",
         "Generated by `eval/make_report.py` from `eval/results/`. Live runs on Gemini via Vertex AI at the global location;",
         "judge model gemini-3.6-flash (balanced tier). Every failing live case was retried once: pass on retry = transient,",
         "fail again = persistent. First attempts are kept as evidence in `eval/results/`.", ""]
    # summary table
    rows = []
    adk_total = sum(v["total"] for v in adk.values())
    adk_first = sum(v["passed_first_attempt"] for v in adk.values())
    adk_after = sum(v["passed_after_retry"] for v in adk.values())
    rows.append(("ADK AgentEvaluator (trajectory + rubric + hallucination)", adk_first, adk_after, adk_total))
    if gr:
        s = gr["summary"]
        rows.append(("Grounding (SQL truth at test time)", s["grounded_first_attempt"], s["grounded_after_retry"], s["total"]))
    if sf:
        s = sf["summary"]
        rows.append(("Safety (injection, refusal, HITL)", s["passed_first_attempt"], s["passed_after_retry"], s["total"]))
    L += ["## Summary", "", "| Suite | Passed first attempt | Passed after one retry | Total |", "|---|---|---|---|"]
    L += [f"| {a} | {b}/{d} | {c}/{d} | {d} |" for a, b, c, d in rows]
    L += [f"| pytest (deterministic) | {pytest_line} | | |", ""]
    readme = ["| Suite | First attempt | After one retry |", "|---|---|---|"] + [f"| {a} | {b}/{d} | {c}/{d} |" for a, b, c, d in rows] \
        + [f"| pytest | {pytest_line} | |"]
    # ADK detail
    L += ["## ADK AgentEvaluator", "",
          "Criteria per case: `tool_trajectory_avg_score` = 1.0 (ANY_ORDER; tool names only for the orchestrator because its",
          "specialist requests are free text, exact arguments for specialists), `rubric_based_final_response_quality_v1` >= 0.8",
          "(3 shared rubrics: citations, units, no execution claim, plus case rubrics), `hallucinations_v1` >= 0.8.",
          "Specialists run as chat-mode clones with identical model, instruction and tools (ADK 2.10 rejects a single-turn",
          "agent as a Runner root); the production single-turn path is the end-to-end set.", "",
          "| Set / file | Agent | Case | Trajectory | Rubric | Hallucination | Result |", "|---|---|---|---|---|---|---|"]
    for key, v in adk.items():
        for cid, c in v["cases"].items():
            m = (c.get("first_attempt") or {}).get("metrics", {})
            g = lambda k: f"{m[k]['status'][0]} {float(m[k]['score']):.2f}" if k in m and m[k]["score"] not in ("", None) else "n/a"  # noqa: E731
            L.append(f"| {key} | {v['agent_name']} | {cid} | {g('tool_trajectory_avg_score')} | {g('rubric_based_final_response_quality_v1')} | "
                     f"{g('hallucinations_v1')} | {c['classification']} |")
        if v.get("first_error") and v["passed_first_attempt"] < v["total"]:
            L.append(f"| {key} | | evaluator message | | | | {str(v['first_error'])[:160].replace('|', '/')} |")
    L.append("")
    # grounding
    if gr:
        L += ["## Grounding", "", "Truth is recomputed at test time (SQL through the same DataStore; LP figures by deterministic",
              "recompute). A case is GROUNDED only if every required tool was called and every key fact is in the answer within",
              "tolerance. UNVERIFIABLE is reported, never dropped.", "",
              "| Scenario | First attempt | Retry | Classification | Latency s | Key facts (truth -> matched) |", "|---|---|---|---|---|---|"]
        for sid, c in sorted(gr["cases"].items(), key=lambda x: int(x[0][1:])):
            f = c["first_attempt"]
            facts = "; ".join(f"{x['name']}: {round(x['truth'], 2) if isinstance(x.get('truth'), (int, float)) else ''} {'ok' if x['matched'] else 'MISSING'}"
                              for x in f.get("facts", []))
            L.append(f"| {sid} | {f['label']} | {(c.get('retry') or {}).get('label', '')} | {c['classification']} | {f.get('latency_s')} | {facts} |")
        L.append("")
    if sf:
        L += ["## Safety", "", "| Case | Description | Classification | Checks (first attempt) |", "|---|---|---|---|"]
        for cid, c in sf["cases"].items():
            checks = "; ".join(("ok " if x["ok"] else "FAIL ") + x["detail"] for x in c["first_attempt"]["checks"])
            L.append(f"| {cid} | {c['desc']} | {c['classification']} | {checks.replace('|', '/')[:400]} |")
        L.append("")
    skipped = ["`tests/test_bigquery_backend.py::test_bigquery_matches_local`: skipped (runs only with DATA_BACKEND=bigquery; no deploy in this build)"]
    L += ["## Skipped and excluded", ""] + [f"- {s}" for s in skipped] + [""]
    if notes:
        L += [notes.strip(), ""]
    open(os.path.join(ROOT, "docs", "EVAL_REPORT.md"), "w").write("\n".join(L))
    rp = os.path.join(ROOT, "README.md")
    txt = open(rp).read()
    txt = re.sub(r"<!-- EVAL:BEGIN -->.*<!-- EVAL:END -->", "<!-- EVAL:BEGIN -->\n" + "\n".join(readme) + "\n<!-- EVAL:END -->", txt, flags=re.S)
    open(rp, "w").write(txt)
    print("\n".join(readme))


if __name__ == "__main__":
    main()
