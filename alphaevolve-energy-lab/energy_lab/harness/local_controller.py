"""Local Gemini-driven evolutionary controller that speaks the AlphaEvolve contract.

This is NOT AlphaEvolve. It exists so real, budgeted, evidence-producing runs can happen today while
the Gemini Enterprise app with AlphaEvolve is not provisioned. It uses the same evaluator contract,
EVOLVE-BLOCK packaging, sandbox, baseline lock, budget ledger, holdout rescoring and evidence schema as
the production adapter (alphaevolve_adapter.py), so switching is one flag (``--backend alphaevolve``).
Evidence carries ``source: "local-gemini-controller"``; ``evolved`` never flips for these runs.

Search: islands (default 3) with a MAP-Elites-lite archive per island over a 2-D behaviour descriptor
supplied by the problem; parent = rank-weighted exploit (60%) or random elite (40%); inspirations = the
island's top programs + an elite from another island + the global best; ring migration every 10
programs. Mutations are AlphaEvolve SEARCH/REPLACE diffs inside the EVOLVE-BLOCK, generated by a
weighted model mix (balanced 0.7 / reasoning 0.3).
"""
